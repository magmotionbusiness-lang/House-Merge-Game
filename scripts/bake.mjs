// Bakes every tier: 256 px thumbnails (public/thumbs), .glb files (art/models),
// the tier-lineup readability sheet (docs/tier-lineup.png) and a stats table.
// Usage: npm run models:bake
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const require = createRequire(import.meta.url);
let chromium;
try {
  ({ chromium } = require('playwright'));
} catch {
  ({ chromium } = await import('playwright'));
}

const server = await createServer({ server: { port: 5199, strictPort: false }, logLevel: 'error' });
await server.listen();
const url = server.resolvedUrls.local[0] + 'bake.html';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error('page error:', e.message));
  await page.goto(url);
  await page.waitForFunction(() => window.__bake, null, { timeout: 120000 });
  const res = await page.evaluate(() => window.__bake);
  if (res.error) throw new Error(res.error);

  const names = res.stats.map((s) => s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-'));
  mkdirSync('public/thumbs', { recursive: true });
  mkdirSync('art/models', { recursive: true });
  mkdirSync('docs', { recursive: true });
  const png = (d) => Buffer.from(d.split(',')[1], 'base64');
  res.thumbs.forEach((d, i) => writeFileSync(`public/thumbs/tier-${String(i + 1).padStart(2, '0')}.png`, png(d)));
  res.glbs.forEach((b, i) => writeFileSync(`art/models/tier-${String(i + 1).padStart(2, '0')}-${names[i]}.glb`, Buffer.from(b, 'base64')));
  writeFileSync('docs/tier-lineup.png', png(res.sheet));

  const rows = res.stats.map((s) => `| ${s.tier} | ${s.name} | ${s.tris} | ${s.draws} |`).join('\n');
  writeFileSync(
    'docs/tier-stats.md',
    `# Tier model stats\n\nGenerated by \`npm run models:bake\`. Budget: under 2,000 triangles for tiers 1-10, under 6,000 for 11-18.\n\n| Tier | Name | Triangles | Draw calls |\n|---|---|---|---|\n${rows}\n`,
  );
  console.table(res.stats);
  const over = res.stats.filter((s) => s.tris > (s.tier <= 10 ? 2000 : 6000));
  if (over.length) {
    console.error('Over triangle budget:', over.map((s) => s.name).join(', '));
    process.exitCode = 1;
  }
} finally {
  await browser.close();
  await server.close();
}
